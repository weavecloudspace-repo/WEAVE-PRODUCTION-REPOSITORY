"""Bounded, privacy-safe per-request trace for CBT AI hybrid generation.

One JSON object per line in logs/cbt_ai_hybrid_trace.jsonl. Deliberately do
NOT store teacher prompts, answers, access tokens, headers, or generated bytes.
A plain FileHandler avoids WinError 32 during RotatingFileHandler rollover on
Windows development workers. Logs on ephemeral hosting require log collection.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import sys
from contextlib import contextmanager
from contextvars import ContextVar
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator

from app.config.settings import BASE_DIR

TRACE_LOG_FILE = Path(BASE_DIR) / "logs" / "cbt_ai_hybrid_trace.jsonl"
_CONTEXT: ContextVar[dict[str, str] | None] = ContextVar("cbt_ai_trace_context", default=None)
_IMAGE: ContextVar[str | None] = ContextVar("cbt_ai_trace_image", default=None)
_LOGGER_NAME = "weave.cbt.ai.hybrid_trace"

# Trace a bounded set of structural metadata ONLY. New fields must be reviewed
# here to prevent accidentally logging prompt text, answers, keys or image data.
SAFE_FIELDS = frozenset(
    {
        "question_count", "visual_mode", "visual_target", "visual_count", "text_count",
        "batch_count", "batch_index", "batch_size", "question_index",
        "option_index", "image_count", "image_bytes", "image_width",
        "image_height", "attempt", "max_attempts", "retryable",
        "retry_delay_seconds", "duration_ms", "queue_ms", "http_status",
        "question_type_single", "question_type_multiple", "repaired",
        "input_tokens", "output_tokens", "provider_cost", "credits",
        "credits_charged", "credits_released", "expected_count",
        "actual_count", "error_type", "status", "model", "endpoint",
        "stage", "reason", "finish_reason", "validation_issue_count",
        "issue_codes", "idempotency_status", "created", "response_bytes",
        "timeout_seconds", "source", "request_stage", "quota_status",
    }
)
_STRING_FIELDS = frozenset(
    {
        "error_type", "status", "model", "endpoint", "stage", "reason", "visual_mode",
        "finish_reason", "idempotency_status", "source", "request_stage",
        "quota_status",
    }
)
_ENABLED = os.getenv("WEAVE_CBT_AI_TRACE_ENABLED", "true").strip().lower() not in {
    "0", "false", "off", "no"
}


def _trace_logger() -> logging.Logger:
    logger = logging.getLogger(_LOGGER_NAME)
    if logger.handlers:
        return logger
    logger.setLevel(logging.INFO)
    logger.propagate = False
    try:
        TRACE_LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
        handler: logging.Handler = logging.FileHandler(
            TRACE_LOG_FILE, mode="a", encoding="utf-8"
        )
    except OSError:
        # Diagnostics must never break live authoring if the filesystem is read-only.
        handler = logging.StreamHandler(sys.stderr)
    handler.setFormatter(logging.Formatter("%(message)s"))
    logger.addHandler(handler)
    return logger


def _short_hash(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:16]


@contextmanager
def trace_request(
    *, idempotency_key: str, operation: str, request_id: str | None = None
) -> Iterator[None]:
    """Bind one inbound HTTP attempt. Retries share operation_id."""
    token = _CONTEXT.set(
        {
            "operation_id": _short_hash(idempotency_key),
            "request_id": str(request_id or "unavailable")[:72],
            "operation": operation,
        }
    )
    try:
        yield
    finally:
        _CONTEXT.reset(token)


@contextmanager
def trace_image(image_ref: str) -> Iterator[None]:
    """Identify one image across concurrent asynchronous tasks and retries."""
    token = _IMAGE.set(image_ref[:64])
    try:
        yield
    finally:
        _IMAGE.reset(token)


def trace_event(event: str, **fields: Any) -> None:
    """Emit one structured, allowlisted event without capturing unsafe data."""
    if not _ENABLED:
        return
    context = _CONTEXT.get()
    if context is None:
        return

    clean: dict[str, Any] = {}
    for key, value in fields.items():
        if key not in SAFE_FIELDS or value is None:
            continue
        if isinstance(value, bool):
            clean[key] = value
        elif isinstance(value, (int, float)):
            clean[key] = round(value, 3) if isinstance(value, float) else value
        elif key in _STRING_FIELDS and isinstance(value, str):
            # Only static internal descriptors should be passed by callers.
            clean[key] = value[:100]
        elif key == "issue_codes" and isinstance(value, (list, tuple)):
            clean[key] = [
                str(code)[:48] for code in value[:12] if isinstance(code, str)
            ]
    payload = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "event": event[:90],
        **context,
        **({"image_ref": _IMAGE.get()} if _IMAGE.get() is not None else {}),
        **clean,
    }
    try:
        _trace_logger().info(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))
    except (OSError, ValueError, TypeError):
        # Tracing is diagnostic only and cannot break question generation.
        pass
